                                 <p class="mt-2">Mental health is the most important aspect of any child’s social and cognitive development. Therefore, the Guidance and Counselling Cell desires and strives to ensure health and vitality. It provides the students with supportive environment to succeed academically, socially and emotionally.</p>
                                 <p class="mt-2">Guidance and Counselling Cell is an initiative by DPS Eldeco, that works with an objective to provide assistance to students, parents and teachers in order to promote positive mental health in school environment.</p>
